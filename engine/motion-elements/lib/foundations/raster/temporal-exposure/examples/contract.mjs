import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import * as api from '../../../../index.mjs';
const catalog=JSON.parse(readFileSync(new URL('../../../../../catalog.json',import.meta.url)));
const item=catalog.elements.find(e=>e.id==='raster.temporal-exposure');
assert(item);
const plan=api.compileTemporalExposure(item.example);
const reads=[];const readFrame=frame=>{reads.push(frame);return new Uint8ClampedArray(frame?[255,0,0,255]:[0,0,255,255]);};
const result=api.sampleTemporalExposure(plan,1,{width:1,height:1,readFrame});
assert.deepEqual([...result.data],[64,0,191,255]);assert.deepEqual(reads,[1,0]);
const start=api.sampleTemporalExposure(plan,0,{width:1,height:1,readFrame});
assert.deepEqual([...start.data],[0,0,255,64]);
const opaque=api.compileTemporalExposure({...item.example,boundary:'clamp-start'});
let calls=0;const clamped=api.sampleTemporalExposure(opaque,0,{width:1,height:1,readFrame(){calls++;return new Uint8ClampedArray([0,0,255,255]);}});
assert.equal(calls,1);assert.deepEqual([...clamped.data],[0,0,255,255]);
result.data[0]=99;assert.deepEqual([...api.sampleTemporalExposure(plan,1,{width:1,height:1,readFrame}).data],[64,0,191,255]);
assert.throws(()=>api.compileTemporalExposure({offsets:[0,0],weights:[1,1]}));
assert.throws(()=>api.sampleTemporalExposure(plan,1,{width:1,height:1,readFrame:()=>new Uint8Array(4)}));
console.log('raster.temporal-exposure contract PASS');
