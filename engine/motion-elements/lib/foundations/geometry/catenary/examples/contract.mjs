import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import * as api from '../../../../index.mjs';
const catalog=JSON.parse(readFileSync(new URL('../../../../../catalog.json',import.meta.url)));
const item=catalog.elements.find(e=>e.id==='geometry.catenary');
assert(item);
const plan=api.compileCatenary(item.example);
assert.deepEqual(api.sampleCatenary(plan,0).position,item.example.from);
assert.deepEqual(api.sampleCatenary(plan,1).position,item.example.to);
const symmetric=api.compileCatenary({from:{x:0,y:0},to:{x:800,y:0},length:1000,gravity:{x:0,y:1}});
const middle=api.sampleCatenary(symmetric,.5);
assert(Math.abs(middle.position.x-400)<1e-10);assert(middle.position.y>250);
assert(Math.abs(middle.tangent.x-1)<1e-12);assert(Math.abs(middle.tangent.y)<1e-12);
const line=api.compileCatenary({from:{x:0,y:0},to:{x:3,y:4},length:5,gravity:{x:0,y:1}});
assert.equal(line.kind,'taut');
const straight=api.sampleCatenary(line,.4).position;
assert(Math.abs(straight.x-1.2)<1e-12);assert(Math.abs(straight.y-1.6)<1e-12);
const before=api.sampleCatenary(plan,.3);api.sampleCatenary(plan,.8);assert.deepEqual(before,api.sampleCatenary(plan,.3));
assert.throws(()=>api.sampleCatenary(JSON.parse(JSON.stringify(plan)),.3));
assert.throws(()=>api.compileCatenary({...item.example,length:1}));
console.log('geometry.catenary contract PASS');
